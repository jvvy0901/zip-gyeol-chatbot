def run(k: int = 6, verbose: bool = True) -> float:
    chunks = load_chunks()
    pinned = {c.id for c in pinned_chunks(chunks)}
    bm25 = BM25(chunks)
    ok = 0
    for q, expected in CASES:
        hits = bm25.search(q, k=k, exclude=pinned)
        got = pinned | {h.chunk.id for h in hits}
        hit = bool(expected & got)
        ok += hit
        if verbose and not hit:
            top = ", ".join(f"{h.chunk.id}({h.score:.1f})" for h in hits[:4])
            print(f"  MISS  {q}  정답={sorted(expected)}  검색={top}")
    rate = ok / len(CASES)
    print(f"recall@{k} (+고정 {len(pinned)}개): {ok}/{len(CASES)} = {rate:.0%}")
    return rate


def test_recall():
    assert run(verbose=False) >= 0.9


if __name__ == "__main__":
    for k in (3, 6, 8):
        run(k, verbose=(k == 6))
